"""Upload encrypted evidence only. No Actions artifacts, cache, Packages or LFS."""
import datetime as dt
import json
import os
from pathlib import Path
import subprocess
import uuid
import zipfile

receipt=json.loads(Path('private-output/receipt.json').read_text())
request=receipt['request']
request_id=str(uuid.UUID(request['requestId']))
created=dt.datetime.fromisoformat(request['createdAt'])
tag='evidence-'+created.astimezone(dt.timezone.utc).strftime('%Y-%m')
run_id=os.environ['GITHUB_RUN_ID']
attempt=os.environ['GITHUB_RUN_ATTEMPT']
if not run_id.isdecimal() or not attempt.isdecimal() or int(run_id)<=0 or int(attempt)<=0:
    raise ValueError('invalid_run_identity')
asset=Path(request_id+'-'+run_id+'-'+attempt+'.zip')
bundle=Path(os.environ['ATTESTATION_BUNDLE'])
if not bundle.is_file() or bundle.stat().st_size>2000000:
    raise ValueError('invalid_attestation_bundle')
if not Path('evidence.cms').is_file() or Path('evidence.cms').stat().st_size>12000000:
    raise ValueError('invalid_encrypted_asset')
with zipfile.ZipFile(asset,'x',compression=zipfile.ZIP_DEFLATED) as archive:
    archive.write('evidence.cms','evidence.cms')
    archive.write(bundle,'attestation.sigstore.json')
# Serial concurrency avoids two writers creating the same monthly release.
if subprocess.run(['gh','release','view',tag],stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL).returncode:
    subprocess.run(['gh','release','create',tag,'--target',receipt['sourceCommit'],
                    '--title',tag,'--notes','Encrypted evidence generated by this collector.'],check=True,
                   stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL)
# No clobber: an existing request's evidence is immutable.
subprocess.run(['gh','release','upload',tag,str(asset)],check=True,
               stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL)
